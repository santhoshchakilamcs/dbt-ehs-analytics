select
    report_id,
    md5(coalesce(lower(employer_name), '') || '|' || coalesce(lower(city), '') || '|' || coalesce(upper(state), '')) as employer_key,
    event_date,
    year(event_date) as event_year,
    month(event_date) as event_month,
    employer_name,
    address1,
    address2,
    city,
    state,
    zip_code,
    latitude,
    longitude,
    naics_code,
    {{ naics_sector('naics_code') }} as naics_sector,
    coalesce(people_hospitalized, 0) as people_hospitalized,
    coalesce(people_amputated, 0) as people_amputated,
    coalesce(people_eye_loss, 0) as people_eye_loss,
    case when coalesce(people_hospitalized, 0) > 0 then 1 else 0 end as is_hospitalized,
    case when coalesce(people_amputated, 0) > 0 then 1 else 0 end as is_amputation,
    case when coalesce(people_eye_loss, 0) > 0 then 1 else 0 end as is_eye_loss,
    case when inspection_nr is not null then 1 else 0 end as has_inspection,
    inspection_nr,
    narrative,
    coalesce(nature_code, 'UNKNOWN') as nature_code,
    coalesce(nature_title, 'Unknown / not reported') as nature_title,
    coalesce(body_part_code, 'UNKNOWN') as body_part_code,
    coalesce(body_part_title, 'Unknown / not reported') as body_part_title,
    coalesce(event_code, 'UNKNOWN') as event_code,
    coalesce(event_title, 'Unknown / not reported') as event_title,
    coalesce(source_code, 'UNKNOWN') as source_code,
    coalesce(source_title, 'Unknown / not reported') as source_title,
    coalesce(secondary_source_code, 'UNKNOWN') as secondary_source_code,
    coalesce(secondary_source_title, 'Unknown / not reported') as secondary_source_title,
    is_federal,
    {{ severity_score('people_hospitalized', 'people_amputated', 'people_eye_loss') }} as severity_score
from {{ ref('stg_osha_sir') }}
